#!/usr/bin/env node
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { createI18n } from '../src/i18n/runtime.mjs';
import { createDiscordLabelParser } from '../src/discord-dom-labels.mjs';

const root = new URL('../', import.meta.url);
const read = (file) => fs.readFileSync(new URL(file, root), 'utf8').replaceAll('\r\n', '\n');
const localeDir = 'src/i18n/locales/';
const output = new URL('discord-chat-exporter.user.js', root);

export function readCatalog() {
  const codes = fs.readdirSync(new URL(localeDir, root))
    .filter((file) => file.endsWith('.json')).map((file) => file.slice(0, -5)).sort();
  return Object.fromEntries(codes.map((code) => [code, JSON.parse(read(localeDir + code + '.json'))]));
}

export function buildUserscript(catalog = readCatalog()) {
  const header = read('src/userscript-header.txt');
  const version = header.match(/^\/\/ @version\s+(\S+)$/m)?.[1];
  const metadata = ['name', 'description'].flatMap((field) => [
    ['en', catalog.en], ...Object.entries(catalog).filter(([code]) => code !== 'en')
  ].map(([code, entry]) => {
    const key = '@' + field + (code === 'en' ? '' : ':' + code);
    const value = entry[field];
    if (typeof value !== 'string' || !value.trim() || /[\r\n]/.test(value)) {
      throw new Error(`${code}: invalid ${field} metadata`);
    }
    return '// ' + key.padEnd(14) + (key.length >= 14 ? ' ' : '') + value;
  }));
  const runtimeCatalog = Object.fromEntries(Object.entries(catalog).map(([code, { name, description, ...entry }]) => [code, entry]));
  const bundle = [
    '// Generated by scripts/build.mjs. Edit the sources in src/.',
    createI18n.toString(), '', createDiscordLabelParser.toString(), '',
    'const i18n = createI18n(' + JSON.stringify(runtimeCatalog, null, 2) + ');',
    'const VERSION = ' + JSON.stringify(version) + ';'
  ].join('\n').replaceAll('\r\n', '\n').split('\n').map((line) => line ? '  ' + line : '').join('\n');
  const source = read('src/exporter.js');
  const marker = '  /* @bundle */';
  if (!version || source.split(marker).length !== 2 || !header.includes('// ==UserScript==\n')) {
    throw new Error('Missing version or build marker');
  }
  return header.replace('// ==UserScript==\n', (line) => line + metadata.join('\n') + '\n')
    + '\n' + source.replace(marker, () => bundle);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv[2] === '--check') {
    if (buildUserscript() !== read('discord-chat-exporter.user.js')) {
      console.error('The userscript is out of date. Run node scripts/build.mjs.');
      process.exitCode = 1;
    } else {
      console.log('The userscript matches its sources.');
    }
  } else {
    fs.writeFileSync(output, buildUserscript());
    console.log('Built discord-chat-exporter.user.js');
  }
}
